use super::*;
use ctypes::vote::{PRECOMMIT_TYPE, PREVOTE_TYPE};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum DirectoryFault {
    Open,
    Sync,
}

thread_local! {
    static DIRECTORY_FAULT: std::cell::Cell<Option<DirectoryFault>> = const {
        std::cell::Cell::new(None)
    };
}

pub(super) fn directory_fault(stage: DirectoryFault) -> std::io::Result<()> {
    DIRECTORY_FAULT.with(|fault| {
        if fault.get() == Some(stage) {
            fault.set(None);
            Err(std::io::Error::other(format!(
                "injected directory {stage:?} failure"
            )))
        } else {
            Ok(())
        }
    })
}

struct DirectoryFaultGuard;

impl DirectoryFaultGuard {
    fn new(stage: DirectoryFault) -> Self {
        DIRECTORY_FAULT.with(|fault| assert!(fault.replace(Some(stage)).is_none()));
        Self
    }
}

impl Drop for DirectoryFaultGuard {
    fn drop(&mut self) {
        DIRECTORY_FAULT.with(|fault| fault.set(None));
    }
}

fn sha(b: &[u8]) -> Vec<u8> {
    hash::sha256(b).to_vec()
}

fn block_id(n: u8) -> pb::BlockId {
    if n == 0 {
        return pb::BlockId::default();
    }
    let h = sha(&[n]);
    pb::BlockId {
        hash: h.clone(),
        part_set_header: Some(pb::PartSetHeader {
            total: u32::from(n) * 3,
            hash: sha(&h),
        }),
    }
}

fn ts(seconds: i64, nanos: i32) -> Option<pbjson_types::Timestamp> {
    Some(pbjson_types::Timestamp { seconds, nanos })
}

fn temp_pv() -> (FilePv, tempfile::TempDir) {
    let dir = tempfile::tempdir().unwrap();
    let pv = FilePv::generate(dir.path().join("key.json"), dir.path().join("state.json")).unwrap();
    pv.save().unwrap();
    (pv, dir)
}

fn vote(pv: &FilePv, t: i32, h: i64, r: i32, b: u8) -> pb::Vote {
    pb::Vote {
        r#type: t,
        height: h,
        round: r,
        block_id: Some(block_id(b)),
        timestamp: ts(1_700_000_000, 0),
        validator_address: pv.address().to_vec(),
        validator_index: 0,
        ..Default::default()
    }
}

#[test]
fn gen_load_validator() {
    let (mut pv, dir) = temp_pv();
    pv.last_sign_state.height = 100;
    pv.save().unwrap();
    let addr = pv.address().to_vec();
    let pv2 = FilePv::load(dir.path().join("key.json"), dir.path().join("state.json")).unwrap();
    assert_eq!(pv2.address(), addr.as_slice());
    assert_eq!(pv2.last_sign_state.height, 100);
}

#[test]
fn reset_validator() {
    let (mut pv, _dir) = temp_pv();
    let empty = pv.last_sign_state.clone();
    let mut v = vote(&pv, PREVOTE_TYPE, 10, 1, 1);
    pv.sign_vote("mychainid", &mut v).unwrap();
    assert_ne!(pv.last_sign_state, empty);
    pv.reset().unwrap();
    assert_eq!(pv.last_sign_state, empty);
}

