#[test]
fn sign_vote() {
    let (mut pv, _dir) = temp_pv();
    for t in [PREVOTE_TYPE, PRECOMMIT_TYPE] {
        let h = if t == PREVOTE_TYPE { 10 } else { 11 };
        let mut v = vote(&pv, t, h, 1, 1);
        pv.sign_vote("mychainid", &mut v).unwrap();
        let sig = v.signature.clone();
        // Same vote again: fine, same signature.
        pv.sign_vote("mychainid", &mut v).unwrap();
        assert_eq!(v.signature, sig);
        // Bad votes: round regression, height regression, both, different block.
        for mut bad in [
            vote(&pv, t, h, 0, 1),
            vote(&pv, t, h - 1, 1, 1),
            vote(&pv, t, h - 2, 5, 1),
            vote(&pv, t, h, 1, 2),
        ] {
            assert!(pv.sign_vote("mychainid", &mut bad).is_err());
        }
        // Different timestamp: old signature and timestamp come back.
        let mut v2 = v.clone();
        v2.timestamp = ts(1_700_000_000, 1000);
        pv.sign_vote("mychainid", &mut v2).unwrap();
        assert_eq!(v2.signature, sig);
        assert_eq!(v2.timestamp, v.timestamp);
    }
}

#[test]
fn sign_proposal() {
    let (mut pv, _dir) = temp_pv();
    let prop = |h: i64, r: i32, b: u8| pb::Proposal {
        r#type: ctypes::vote::PROPOSAL_TYPE,
        height: h,
        round: r,
        pol_round: -1,
        block_id: Some(block_id(b)),
        timestamp: ts(1_700_000_000, 0),
        signature: vec![],
    };
    let mut p = prop(10, 1, 1);
    pv.sign_proposal("mychainid", &mut p).unwrap();
    let sig = p.signature.clone();
    pv.sign_proposal("mychainid", &mut p).unwrap();
    assert_eq!(p.signature, sig);
    for mut bad in [prop(10, 0, 1), prop(9, 1, 1), prop(8, 5, 1), prop(10, 1, 2)] {
        assert!(pv.sign_proposal("mychainid", &mut bad).is_err());
    }
    let mut p2 = p.clone();
    p2.timestamp = ts(1_700_000_000, 1);
    pv.sign_proposal("mychainid", &mut p2).unwrap();
    assert_eq!(p2.signature, sig);
    assert_eq!(p2.timestamp, p.timestamp);
}

#[test]
fn vote_extensions_are_always_signed() {
    let (mut pv, _dir) = temp_pv();
    let pk = pv.key.pub_key();
    let mut v = vote(&pv, PRECOMMIT_TYPE, 1, 0, 1);
    v.extension = b"extension".to_vec();
    pv.sign_vote("mychainid", &mut v).unwrap();
    assert!(!v.extension_signature.is_empty());
    let ext_bytes = vote_extension_sign_bytes("mychainid", &v);
    assert!(pk.verify_signature(&ext_bytes, &v.extension_signature));
    // Re-signing the same vote with a different extension: the vote
    // signature is reused, the extension is signed anew.
    let mut v2 = v.clone();
    v2.extension = b"new extension".to_vec();
    v2.extension_signature.clear();
    pv.sign_vote("mychainid", &mut v2).unwrap();
    assert_eq!(v2.signature, v.signature);
    let ext2 = vote_extension_sign_bytes("mychainid", &v2);
    assert!(pk.verify_signature(&ext2, &v2.extension_signature));
    // Prevotes never carry an extension signature.
    let mut pre = vote(&pv, PREVOTE_TYPE, 2, 0, 1);
    pv.sign_vote("mychainid", &mut pre).unwrap();
    assert!(pre.extension_signature.is_empty());
}

#[test]
fn state_is_persisted_before_signature_returned() {
    let (mut pv, dir) = temp_pv();
    let mut v = vote(&pv, PREVOTE_TYPE, 5, 0, 1);
    pv.sign_vote("c", &mut v).unwrap();
    // A "restarted" signer sees the state and refuses a conflicting vote.
    let mut pv2 = FilePv::load(dir.path().join("key.json"), dir.path().join("state.json")).unwrap();
    let mut conflict = vote(&pv2, PREVOTE_TYPE, 5, 0, 2);
    assert_eq!(
        pv2.sign_vote("c", &mut conflict).unwrap_err().0,
        "error signing vote: conflicting data"
    );
    let mut same = vote(&pv2, PREVOTE_TYPE, 5, 0, 1);
    pv2.sign_vote("c", &mut same).unwrap();
    assert_eq!(same.signature, v.signature);
}

#[test]
fn failed_state_write_releases_no_vote_or_extension_signature() {
    let (mut pv, dir) = temp_pv();
    let before = pv.last_sign_state.clone();
    let state_path = dir.path().join("state.json");
    let persisted = fs::read(&state_path).unwrap();
    // Force the atomic writer's open to fail, even when tests run as root.
    let blocker = dir
        .path()
        .join(format!(".state.json.tmp{}", std::process::id()));
    fs::create_dir(&blocker).unwrap();
    let mut v = vote(&pv, PRECOMMIT_TYPE, 5, 0, 1);
    v.extension = b"extension".to_vec();
    assert!(pv.sign_vote("c", &mut v).is_err());
    assert!(v.signature.is_empty());
    assert!(v.extension_signature.is_empty());
    assert_eq!(pv.last_sign_state, before);
    assert_eq!(fs::read(&state_path).unwrap(), persisted);

    fs::remove_dir(blocker).unwrap();
    pv.sign_vote("c", &mut v).unwrap();
    assert!(!v.signature.is_empty());
    assert!(!v.extension_signature.is_empty());
    let mut restarted = FilePv::load(dir.path().join("key.json"), state_path).unwrap();
    let mut conflict = vote(&restarted, PRECOMMIT_TYPE, 5, 0, 2);
    assert!(restarted.sign_vote("c", &mut conflict).is_err());
    assert!(conflict.signature.is_empty());
}

