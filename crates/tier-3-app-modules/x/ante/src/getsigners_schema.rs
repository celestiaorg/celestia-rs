//! How celestia-appd's `Tx.GetSigners` decodes each message type
//! (cosmos-proto `anyutil.Unpack`), dumped from the Go binary by the
//! differential fuzzer's oracle (`conformance/fuzzoracle`, ops `v2types`
//! and `utf8schema`) for celestia-app v10.4.0; v9.0.8's tables are a
//! subset (no fibre / valaddr types, no `MsgCreateNativeSyntheticToken`,
//! no `MsgForward` fields 7 / 8). Regenerate with
//! `crates/fuzz-diff/gen-getsigners-schema.sh`.
//!
//! A type `protoregistry.GlobalTypes` resolves ([`PROTOV2_TYPES`]) is
//! decoded with its generated (pulsar) unmarshal, which keeps invalid UTF-8
//! in strings like gogoproto. Every other type is decoded with `dynamicpb`
//! over the descriptor the interface registry resolves ([`DYNAMIC_ROOTS`]),
//! which rejects invalid UTF-8 exactly in the string fields whose
//! descriptor is proto3 ([`STRING_FIELDS`], reached through
//! [`MESSAGE_FIELDS`]); e.g. ibc's `UpgradeFields` resolves without proto3
//! syntax and is not checked. `dynamicpb` also rejects varints protobuf-go
//! cannot parse (a 10th byte above 1) that gogoproto accepts, including the
//! elements of packed repeated scalars ([`PACKED_FIELDS`]).

