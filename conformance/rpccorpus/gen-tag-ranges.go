// Regenerate the Unicode table used by the RPC event query scanner.
// From the repository root, run with the celestia-app Go toolchain:
// go run conformance/rpccorpus/gen-tag-ranges.go | rustfmt --emit stdout > crates/tier-4-runtime/rpc/src/query_tag_ranges.rs
package main

import (
	"fmt"
	"unicode"
)

func main() {
	fmt.Printf("// Generated by conformance/rpccorpus/gen-tag-ranges.go with Unicode %s.\n", unicode.Version)
	fmt.Println("// Half-open ranges for non-ASCII letters and decimal digits, stored as pairs of boundaries.")
	fmt.Println("pub(super) const BOUNDARIES: &[u32] = &[")
	inside := false
	for r := rune(128); r <= unicode.MaxRune+1; r++ {
		member := unicode.IsLetter(r) || unicode.IsDigit(r)
		if member != inside {
			fmt.Printf("0x%x,\n", r)
			inside = member
		}
	}
	fmt.Println("];")
}
