package main

import (
	"fmt"
	"log"
	"os"
	"sort"
	"strings"
)

// rustInterfaces maps the Go interface types that UnpackInterfaces
// implementations reachable from a tx unpack against to Rust `Iface` bits.
var rustInterfaces = []struct {
	goType string
	rust   string
}{
	{".", "MSG"}, // sdk.Msg (an alias of the gogoproto Message interface)
	{"github.com/cosmos/cosmos-sdk/crypto/types.PubKey", "PUB_KEY"},
	{"github.com/cosmos/cosmos-sdk/x/authz.Authorization", "AUTHORIZATION"},
	{"cosmossdk.io/x/feegrant.FeeAllowanceI", "FEE_ALLOWANCE"},
	{"github.com/cosmos/cosmos-sdk/x/gov/types/v1beta1.Content", "CONTENT"},
	{"cosmossdk.io/x/evidence/exported.Evidence", "EVIDENCE"},
	{"github.com/cosmos/ibc-go/v8/modules/core/exported.ClientState", "CLIENT_STATE"},
	{"github.com/cosmos/ibc-go/v8/modules/core/exported.ConsensusState", "CONSENSUS_STATE"},
	{"github.com/cosmos/ibc-go/v8/modules/core/exported.ClientMessage", "CLIENT_MESSAGE"},
	{"github.com/cosmos/cosmos-sdk/types/tx.TxExtensionOptionI", "TX_EXTENSION_OPTION"},
}

// writeRustRegistry writes the Rust static interface-registry table.
func writeRustRegistry(path string, s schema) {
	bits := map[string][]string{}
	found := map[string]bool{}
	for _, iface := range s.Interfaces {
		for _, ri := range rustInterfaces {
			if iface.GoType != ri.goType {
				continue
			}
			found[ri.goType] = true
			for _, impl := range iface.Impls {
				bits[impl.TypeURL] = append(bits[impl.TypeURL], "iface::"+ri.rust)
			}
		}
	}
	for _, ri := range rustInterfaces {
		if !found[ri.goType] {
			log.Fatalf("interface %s not registered", ri.goType)
		}
	}
	var b strings.Builder
	b.WriteString("// @generated by conformance/txdecode (`go run . -out ../fixtures/txdecode`). Do not edit.\n")
	b.WriteString("//\n// The celestia-app v10.4.0 interface registry (`encoding.MakeConfig(app.ModuleEncodingRegisters...)`):\n")
	b.WriteString("// every type URL in `typeURLMap` (what `unknownproto` can resolve inside an `Any`),\n")
	b.WriteString("// its message full name, and the interfaces it is registered against.\n\n")
	b.WriteString("/// `(type URL, message full name, interface bits)`, sorted by type URL.\n")
	b.WriteString("pub(crate) static TYPE_URLS: &[(&str, &str, u32)] = &[\n")
	urls := append([]schemaImpl(nil), s.TypeURLs...)
	sort.Slice(urls, func(i, j int) bool { return urls[i].TypeURL < urls[j].TypeURL })
	for _, u := range urls {
		mask := "0"
		if bs := bits[u.TypeURL]; len(bs) > 0 {
			sort.Strings(bs)
			mask = strings.Join(bs, " | ")
		}
		fmt.Fprintf(&b, "    (%q, %q, %s),\n", u.TypeURL, u.Message, mask)
	}
	b.WriteString("];\n")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}
